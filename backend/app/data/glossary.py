def as_list() -> list[dict]:
    """API 응답용 리스트(term 포함) 변환."""
    return [{"term": t, **v} for t, v in GLOSSARY.items()]


def categories() -> list[str]:
    """중복 없는 카테고리 목록(등장 순서 유지)."""
    seen: list[str] = []
    for v in GLOSSARY.values():
        if v["category"] not in seen:
            seen.append(v["category"])
    return seen
