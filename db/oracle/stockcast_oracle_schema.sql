CREATE TABLE plant (
  plant_id    VARCHAR2(4)   NOT NULL,
  name        VARCHAR2(60)  NOT NULL,
  created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_plant PRIMARY KEY (plant_id)
);
COMMENT ON TABLE plant IS '사업장/물류센터 (마스터)';

CREATE TABLE storage_location (
  plant_id  VARCHAR2(4)   NOT NULL,
  sloc_id   VARCHAR2(4)   NOT NULL,
  name      VARCHAR2(60)  NOT NULL,
  CONSTRAINT pk_storage_location PRIMARY KEY (plant_id, sloc_id),
  CONSTRAINT fk_sloc_plant FOREIGN KEY (plant_id) REFERENCES plant(plant_id)
);
COMMENT ON TABLE storage_location IS '저장위치/창고 (마스터)';

CREATE TABLE material_group (
  group_code VARCHAR2(9)   NOT NULL,
  name       VARCHAR2(60)  NOT NULL,
  CONSTRAINT pk_material_group PRIMARY KEY (group_code)
);
COMMENT ON TABLE material_group IS '자재그룹 (코드성)';

CREATE TABLE material (
  material_no    VARCHAR2(18)  NOT NULL,
  description    VARCHAR2(120) NOT NULL,
  material_type  VARCHAR2(4)   NOT NULL,
  group_code     VARCHAR2(9),
  base_uom       VARCHAR2(3)   DEFAULT 'EA' NOT NULL,
  unit_price     NUMBER(12,2)  DEFAULT 0   NOT NULL,
  created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_material PRIMARY KEY (material_no),
  CONSTRAINT fk_material_group FOREIGN KEY (group_code) REFERENCES material_group(group_code)
);
COMMENT ON TABLE material IS '자재(품목) 마스터 — 단가 포함';

CREATE TABLE movement_type (
  code        VARCHAR2(3)   NOT NULL,
  description VARCHAR2(60)  NOT NULL,
  direction   NUMBER(3)     NOT NULL,
  CONSTRAINT pk_movement_type PRIMARY KEY (code),
  CONSTRAINT ck_mvt_dir CHECK (direction IN (-1, 1))
);
COMMENT ON TABLE movement_type IS '이동유형 (코드성) 101입고/201출고/561기초';

CREATE TABLE stock (
  material_no       VARCHAR2(18) NOT NULL,
  plant_id          VARCHAR2(4)  NOT NULL,
  sloc_id           VARCHAR2(4)  NOT NULL,
  unrestricted_qty  NUMBER(15,3) DEFAULT 0 NOT NULL,
  safety_stock      NUMBER(15,3) DEFAULT 0 NOT NULL,
  reorder_point     NUMBER(15,3) DEFAULT 0 NOT NULL,
  updated_at        TIMESTAMP    DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_stock PRIMARY KEY (material_no, plant_id, sloc_id),
  CONSTRAINT fk_stock_material FOREIGN KEY (material_no) REFERENCES material(material_no),
  CONSTRAINT fk_stock_sloc FOREIGN KEY (plant_id, sloc_id) REFERENCES storage_location(plant_id, sloc_id)
);
COMMENT ON TABLE stock IS '저장위치별 현재고 + 안전재고/재주문점';

CREATE TABLE material_doc_header (
  doc_no       NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
  posting_date DATE         NOT NULL,
  doc_date     DATE         DEFAULT SYSDATE,
  source       VARCHAR2(10) DEFAULT 'NFC',
  created_at   TIMESTAMP    DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_mdh PRIMARY KEY (doc_no)
);
COMMENT ON TABLE material_doc_header IS '자재문서 헤더 (입출고 1건, 거래)';

CREATE TABLE material_doc_item (
  doc_no        NUMBER(19)   NOT NULL,
  item_no       NUMBER(10)   NOT NULL,
  material_no   VARCHAR2(18) NOT NULL,
  plant_id      VARCHAR2(4)  NOT NULL,
  sloc_id       VARCHAR2(4)  NOT NULL,
  movement_type VARCHAR2(3)  NOT NULL,
  quantity      NUMBER(15,3) NOT NULL,
  uom           VARCHAR2(3)  DEFAULT 'EA',
  CONSTRAINT pk_mdi PRIMARY KEY (doc_no, item_no),
  CONSTRAINT fk_mdi_header FOREIGN KEY (doc_no) REFERENCES material_doc_header(doc_no) ON DELETE CASCADE,
  CONSTRAINT fk_mdi_material FOREIGN KEY (material_no) REFERENCES material(material_no),
  CONSTRAINT fk_mdi_mvt FOREIGN KEY (movement_type) REFERENCES movement_type(code),
  CONSTRAINT fk_mdi_sloc FOREIGN KEY (plant_id, sloc_id) REFERENCES storage_location(plant_id, sloc_id),
  CONSTRAINT ck_mdi_qty CHECK (quantity > 0)
);
COMMENT ON TABLE material_doc_item IS '자재문서 품목 라인 (거래)';

CREATE TABLE nfc_tag (
  tag_uid     VARCHAR2(64) NOT NULL,
  material_no VARCHAR2(18) NOT NULL,
  plant_id    VARCHAR2(4)  NOT NULL,
  sloc_id     VARCHAR2(4)  NOT NULL,
  created_at  TIMESTAMP    DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_nfc_tag PRIMARY KEY (tag_uid),
  CONSTRAINT fk_nfc_material FOREIGN KEY (material_no) REFERENCES material(material_no),
  CONSTRAINT fk_nfc_sloc FOREIGN KEY (plant_id, sloc_id) REFERENCES storage_location(plant_id, sloc_id)
);
COMMENT ON TABLE nfc_tag IS 'NFC 태그 UID - 자재 매핑';

CREATE TABLE stock_snapshot_history (
  snapshot_date    DATE         NOT NULL,
  material_no      VARCHAR2(18) NOT NULL,
  plant_id         VARCHAR2(4)  NOT NULL,
  sloc_id          VARCHAR2(4)  NOT NULL,
  unrestricted_qty NUMBER(15,3) NOT NULL,
  created_at       TIMESTAMP    DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_ssh PRIMARY KEY (snapshot_date, material_no, plant_id, sloc_id),
  CONSTRAINT fk_ssh_material FOREIGN KEY (material_no) REFERENCES material(material_no),
  CONSTRAINT fk_ssh_sloc FOREIGN KEY (plant_id, sloc_id) REFERENCES storage_location(plant_id, sloc_id)
);
COMMENT ON TABLE stock_snapshot_history IS '월말 재고 스냅샷 (이력성)';

CREATE TABLE ext_weather (
  obs_date    DATE          NOT NULL,
  region_code VARCHAR2(10)  DEFAULT '108',
  avg_temp    NUMBER(5,2),
  min_temp    NUMBER(5,2),
  max_temp    NUMBER(5,2),
  precip_mm   NUMBER(6,2),
  CONSTRAINT pk_ext_weather PRIMARY KEY (obs_date)
);
COMMENT ON TABLE ext_weather IS '기상청 일별 날씨 (외부 공공데이터)';

CREATE TABLE ext_holiday (
  holiday_date DATE          NOT NULL,
  name         VARCHAR2(60)  NOT NULL,
  is_holiday   NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT pk_ext_holiday PRIMARY KEY (holiday_date),
  CONSTRAINT ck_holiday_bool CHECK (is_holiday IN (0, 1))
);
COMMENT ON TABLE ext_holiday IS '공휴일 (외부 공공데이터, 코드성)';

CREATE TABLE ext_bid_notice (
  bid_no        VARCHAR2(40)  NOT NULL,
