-- ============================================================
-- 설비 유지보수 (SAP PM 구조 차용) — 3개 엔터티
-- 물류센터 설비가 멈추면 입출고 처리량이 멈춘다 → 설비 가동률은 재고 회전의 선행지표.
-- 정비오더 완료 시 사용 부품이 이동유형 261로 material_doc_item에 전기되어
-- 실제 재고가 차감된다(PM ↔ MM 연결점).
-- ============================================================

CREATE TABLE equipment (
  equipment_no   VARCHAR2(18)  NOT NULL,
  name           VARCHAR2(120) NOT NULL,
  category       VARCHAR2(20)  NOT NULL,
  plant_id       VARCHAR2(4)   NOT NULL,
  sloc_id        VARCHAR2(4)   NOT NULL,
  manufacturer   VARCHAR2(60),
  install_date   DATE,
  status         VARCHAR2(6)   DEFAULT 'RUN' NOT NULL,
  pm_cycle_days  NUMBER(10)    DEFAULT 0 NOT NULL,
  last_pm_date   DATE,
  created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_equipment  PRIMARY KEY (equipment_no),
  CONSTRAINT fk_equip_sloc FOREIGN KEY (plant_id, sloc_id)
    REFERENCES storage_location (plant_id, sloc_id),
  CONSTRAINT ck_equip_status CHECK (status IN ('RUN','CHECK','DOWN','SCRAP')),
  CONSTRAINT ck_equip_cycle  CHECK (pm_cycle_days >= 0)
);
COMMENT ON TABLE  equipment IS '설비 마스터 (SAP EQUI+EQKT)';
COMMENT ON COLUMN equipment.status        IS 'RUN 정상 / CHECK 점검중 / DOWN 고장 / SCRAP 폐기';
COMMENT ON COLUMN equipment.pm_cycle_days IS '예방정비 주기(일). 0이면 PM 비대상';
COMMENT ON COLUMN equipment.last_pm_date  IS '최근 예방정비일 — 다음 예정일 = last_pm_date + pm_cycle_days';

CREATE TABLE maintenance_order (
  order_no       NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
  equipment_no   VARCHAR2(18)  NOT NULL,
  order_type     VARCHAR2(2)   DEFAULT 'PM'  NOT NULL,
  status         VARCHAR2(6)   DEFAULT 'REQ' NOT NULL,
  priority       VARCHAR2(1)   DEFAULT 'M'   NOT NULL,
  title          VARCHAR2(200) NOT NULL,
  description    VARCHAR2(500),
  requester      VARCHAR2(40),
  request_date   DATE          NOT NULL,
  planned_date   DATE,
  completed_date DATE,
  labor_cost     NUMBER(14,2)  DEFAULT 0,
  created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_maint_order   PRIMARY KEY (order_no),
  CONSTRAINT fk_maint_equip   FOREIGN KEY (equipment_no)
    REFERENCES equipment (equipment_no),
  CONSTRAINT ck_maint_type    CHECK (order_type IN ('PM','CM')),
  CONSTRAINT ck_maint_status  CHECK (status IN ('REQ','WIP','DONE','CANCEL')),
  CONSTRAINT ck_maint_prio    CHECK (priority IN ('H','M','L'))
);
COMMENT ON TABLE  maintenance_order IS '정비오더 (SAP AUFK/AFIH) — 요청→진행→완료';
COMMENT ON COLUMN maintenance_order.order_type   IS 'PM 예방정비 / CM 사후정비(고장)';
COMMENT ON COLUMN maintenance_order.planned_date IS '정비 예정일 — 지연 판정 기준';

CREATE TABLE maintenance_order_part (
  order_no      NUMBER(19)    NOT NULL,
  item_no       NUMBER(10)    NOT NULL,
  material_no   VARCHAR2(18)  NOT NULL,
  quantity      NUMBER(15,3)  NOT NULL,
  uom           VARCHAR2(3)   DEFAULT 'EA' NOT NULL,
  posted_doc_no NUMBER(19),
  CONSTRAINT pk_maint_part  PRIMARY KEY (order_no, item_no),
  CONSTRAINT fk_part_order  FOREIGN KEY (order_no)
    REFERENCES maintenance_order (order_no),
  CONSTRAINT fk_part_mat    FOREIGN KEY (material_no)
    REFERENCES material (material_no),
  CONSTRAINT ck_part_qty    CHECK (quantity > 0)
);
COMMENT ON TABLE  maintenance_order_part IS '정비 사용자재 (SAP RESB → MSEG 소비)';
COMMENT ON COLUMN maintenance_order_part.posted_doc_no
  IS '전기된 자재문서 번호(이동유형 261). NULL이면 아직 재고에서 빠지지 않은 예약 상태';
